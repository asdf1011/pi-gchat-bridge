test("postJson POSTs JSON to the local server and parses the reply (no undici 300s header deadline)", async () => {
  // A real loopback server: the whole point of postJson is its transport
  // behaviour, which a stub can't cover (headers only arrive at the very end).
  const http = await import("node:http");
  const seen: any[] = [];
  const server = http.createServer((req, res) => {
    const chunks: Buffer[] = [];
    req.on("data", (c: Buffer) => chunks.push(c));
    req.on("end", () => {
      seen.push({ method: req.method, contentType: req.headers["content-type"], body: JSON.parse(Buffer.concat(chunks).toString()) });
      // Reply only after the handler returns, mimicking llama.cpp's buffering.
      setTimeout(() => {
        res.writeHead(200, { "content-type": "application/json" });
        res.end(JSON.stringify({ choices: [{ message: { content: "Fine" } }] }));
      }, 50);
    });
  });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const port = (server.address() as { port: number }).port;
  try {
    const out = (await postJson(`http://127.0.0.1:${port}/v1/chat/completions`, { model: "m", messages: [] }, 5000)) as any;
    assert.equal(out.choices[0].message.content, "Fine");
    assert.equal(seen.length, 1);
    assert.equal(seen[0].method, "POST");
    assert.equal(seen[0].contentType, "application/json");
    assert.equal(seen[0].body.model, "m");
  } finally {
    server.close();
  }
});

test("postJson rejects on a non-2xx with the status in the message", async () => {
  const http = await import("node:http");
  const server = http.createServer((_req, res) => {
    res.writeHead(503, { "content-type": "application/json" });
    res.end('{"error":"model loading"}');
  });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const port = (server.address() as { port: number }).port;
  try {
    await assert.rejects(() => postJson(`http://127.0.0.1:${port}/v1/chat/completions`, {}, 5000), /HTTP 503/);
  } finally {
    server.close();
  }
});

test("postJson gives up on a silent server instead of hanging forever", async () => {
  const http = await import("node:http");
  // Accepts the request and never answers — a stuck llama.cpp slot.
  const server = http.createServer(() => {});
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const port = (server.address() as { port: number }).port;
  try {
    await assert.rejects(() => postJson(`http://127.0.0.1:${port}/v1/chat/completions`, {}, 300), /timed out/);
  } finally {
    server.closeAllConnections?.();
    server.close();
  }
});

test("the re-titled card keeps the model body and swaps only the header", () => {
  const before = JSON.stringify(modelConfirmCard({ ok: true, created: true, modelLabel: "LFM3-VL-2B (local)" }));
  const after = modelConfirmCard({ ok: true, created: true, modelLabel: "LFM3-VL-2B (local)" }, { title: "Noise monitoring sign" });
  const card = (after as any[])[0].card;
  assert.equal(card.header.title, "Noise monitoring sign");
  // Body is byte-identical to the un-titled card, so it still says which model
  // the new conversation is on.
  assert.equal(JSON.stringify(card.sections), JSON.stringify((JSON.parse(before) as any[])[0].card.sections));
  assert.match(JSON.stringify(card.sections), /New conversation on <b>LFM3-VL-2B \(local\)<\/b>/);
});

test("an empty title falls back to the plain 'Model switched' header", () => {
  const card = (modelConfirmCard({ ok: true, created: true, modelLabel: "m" }, { title: "   " }) as any[])[0].card;
  assert.equal(card.header.title, "Model switched");
});

test("a failed switch never shows a topic header", () => {
  const card = (modelConfirmCard({ ok: false, error: "no auth", modelLabel: "m" }, { title: "Noise monitoring sign" }) as any[])[0].card;
  assert.equal(card.header.title, "Couldn't switch model");
});

test("the topic-title eval prompt matches the prompt this code sends (cross-repo drift guard)", () => {
  // evals/ keeps its own copy of the system prompt so its cases stay
  // self-contained. If the two drift, the eval quietly measures a prompt we no
  // longer ship — which is exactly the failure mode evals exist to prevent.
  const evalPrompt = new URL("../evals/cases/topic-title/prompts/title-v3.txt", import.meta.url).pathname;
  if (!fs.existsSync(evalPrompt)) return; // evals/ checked out without cases
  assert.equal(fs.readFileSync(evalPrompt, "utf8").trim(), TOPIC_SYSTEM_PROMPT);
});
