test("cleanTitle strips labels, quotes and trailing punctuation", () => {
  assert.equal(cleanTitle('TITLE: "Disk space check."'), "Disk space check");
  assert.equal(cleanTitle("  Worker\nand a second line"), "Worker");
  assert.equal(cleanTitle("`code fences`"), "code fences");
  assert.equal(cleanTitle("Title:   Adding   thinking levels  "), "Adding thinking levels");
  assert.equal(cleanTitle("   "), undefined);
  assert.equal(cleanTitle(""), undefined);
});

test("cleanTitle keeps long titles but cuts a runaway one at a word boundary", () => {
  const long = "Asking whether it is possible to replace the first conversation entry after the first question and response with a summary of the whole discussion generated by a small local model";
  const cleaned = cleanTitle(long);
  assert.ok(cleaned && cleaned.length <= MAX_TITLE_CHARS);
  assert.ok(!cleaned!.endsWith(" "));
  // Cut at a space, so no half word at the end.
  assert.match(long, new RegExp(`^${cleaned!.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`));
  // A title under the limit is returned untouched.
  assert.equal(cleanTitle("Noise monitoring sign"), "Noise monitoring sign");
});

