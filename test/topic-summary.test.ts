/** Stand-in for the local model server; records the URL/body it was asked to POST. */
function fakePost(reply: unknown, opts?: { fail?: string }) {
  const calls: { url: string; body: any; timeoutMs: number }[] = [];
  const post = async (url: string, body: unknown, timeoutMs: number) => {
    calls.push({ url, body: body as any, timeoutMs });
    if (opts?.fail) throw new Error(opts.fail);
    return reply;
  };
  return { calls, post };
}

